// Writes the Flink SQL scripts in pipeline/flink/sql from shared/queries.ts,
// so the real Flink jobs run exactly the queries the site runs (and that the
// parity test checks).
//   node --experimental-transform-types pipeline/flink/generate.ts
import { writeFileSync } from "node:fs";
import { EXAMPLES, PANELS } from "../../shared/queries.ts";
import { REVERT_PATTERN } from "../../shared/change.ts";
import { flinkDdl } from "../../shared/table.ts";

// Exactly-once sinks: Flink writes each checkpoint's results in one Kafka
// transaction and commits it when the checkpoint completes. The transaction
// timeout must fit under the broker's transaction.max.timeout.ms (15 min).
const exactlyOnce = (topic: string) => `  'sink.delivery-guarantee' = 'exactly-once',
  'sink.transactional-id-prefix' = 'tideline-${topic}',
  'properties.transaction.timeout.ms' = '600000'`;

const kafka = (topic: string) => `  'connector' = 'kafka',
  'topic' = '${topic}',
  'properties.bootstrap.servers' = 'kafka:9092',
  'format' = 'json',
  'json.timestamp-format.standard' = 'ISO-8601',
${exactlyOnce(topic)}`;

const setup = `-- Generated by pipeline/flink/generate.ts from shared/queries.ts. Don't edit by hand.
-- Tables for the Tideline jobs: the change stream from Kafka (Avro, schema in
-- Schema Registry) and one Kafka topic per result. Result topics are written
-- in Kafka transactions, so read them with isolation.level=read_committed.

SET 'table.local-time-zone' = 'UTC';
SET 'execution.checkpointing.interval' = '10 s';
SET 'execution.checkpointing.mode' = 'EXACTLY_ONCE';
SET 'pipeline.name' = 'tideline';

${flinkDdl(
  5,
  `  'connector' = 'kafka',
  'topic' = 'wikimedia.recentchange',
  'properties.bootstrap.servers' = 'kafka:9092',
  'properties.group.id' = 'tideline-flink',
  'scan.startup.mode' = 'earliest-offset',
  'value.format' = 'avro-confluent',
  'value.avro-confluent.url' = 'http://schema-registry:8081'`,
)};

CREATE TABLE tideline_pulse (
  window_start TIMESTAMP(3),
  window_end   TIMESTAMP(3),
  project      STRING,
  changes      BIGINT
) WITH (
${kafka("tideline.pulse")}
);

CREATE TABLE tideline_editors (
  window_start TIMESTAMP(3),
  window_end   TIMESTAMP(3),
  by_people    BIGINT,
  by_bots      BIGINT,
  accounts     BIGINT
) WITH (
${kafka("tideline.editors")}
);

CREATE TABLE tideline_trending (
  window_start TIMESTAMP(3),
  window_end   TIMESTAMP(3),
  server_name  STRING,
  title        STRING,
  edits        BIGINT,
  editors      BIGINT,
  net_bytes    INT,
  rownum       BIGINT
) WITH (
${kafka("tideline.trending")}
);

CREATE TABLE tideline_new_pages (
  event_time   TIMESTAMP_LTZ(3),
  server_name  STRING,
  title        STRING,
  user_name    STRING,
  len_new      INT
) WITH (
${kafka("tideline.new-pages")}
);

-- An updating result goes to a compacted topic: one record per wiki, the
-- latest count wins (upsert-kafka turns -U/+U into keyed upserts).
CREATE TABLE tideline_wiki_totals (
  wiki         STRING,
  changes      BIGINT,
  bot_changes  BIGINT,
  last_change  TIMESTAMP_LTZ(3),
  PRIMARY KEY (wiki) NOT ENFORCED
) WITH (
  'connector' = 'upsert-kafka',
  'topic' = 'tideline.wiki-totals',
  'properties.bootstrap.servers' = 'kafka:9092',
  'key.format' = 'json',
  'value.format' = 'json',
${exactlyOnce("tideline.wiki-totals")}
);

CREATE TABLE tideline_edit_wars (
  wiki         STRING,
  title        STRING,
  first_revert TIMESTAMP_LTZ(3),
  third_revert TIMESTAMP_LTZ(3),
  users        STRING
) WITH (
${kafka("tideline.edit-wars")}
);
`;

const P = REVERT_PATTERN.replace(/'/g, "''");
const wars = `SELECT wiki, title, first_revert, third_revert, users
FROM recentchange
MATCH_RECOGNIZE (
  PARTITION BY wiki, title
  ORDER BY event_time
  MEASURES
    R1.event_time AS first_revert,
    R3.event_time AS third_revert,
    CONCAT(R1.user_name, ', ', R2.user_name, ', ', R3.user_name) AS users
  ONE ROW PER MATCH
  AFTER MATCH SKIP PAST LAST ROW
  PATTERN (R1 O1*? R2 O2*? R3) WITHIN INTERVAL '15' MINUTE
  DEFINE
    R1 AS REGEXP(R1.edit_comment, '${P}'),
    R2 AS REGEXP(R2.edit_comment, '${P}'),
    R3 AS REGEXP(R3.edit_comment, '${P}')
      AND (R2.user_name <> R1.user_name OR R3.user_name <> R1.user_name),
    O1 AS NOT REGEXP(O1.edit_comment, '${P}'),
    O2 AS NOT REGEXP(O2.edit_comment, '${P}')
)`;

const changelog = EXAMPLES.find((e) => e.id === "changelog")!;
const indent = (s: string) => s.replace(/^/gm, "  ");
const jobs = `-- Generated by pipeline/flink/generate.ts from shared/queries.ts. Don't edit by hand.
-- All Tideline queries as one Flink job (one source read, six results).

EXECUTE STATEMENT SET
BEGIN

-- ${PANELS.pulse.title}
INSERT INTO tideline_pulse
${indent(PANELS.pulse.sql)};

-- ${PANELS.editors.title}
INSERT INTO tideline_editors
${indent(PANELS.editors.sql)};

-- ${PANELS.trending.title}
INSERT INTO tideline_trending
${indent(PANELS.trending.sql)};

-- ${PANELS.newPages.title}
INSERT INTO tideline_new_pages
${indent(PANELS.newPages.sql)};

-- ${changelog.title}
INSERT INTO tideline_wiki_totals
${indent(changelog.sql)};

-- Edit wars: three reverts in a row on one page by at least two people within 15 minutes
INSERT INTO tideline_edit_wars
${indent(wars)};

END;
`;
writeFileSync(new URL("./sql/00_tables.sql", import.meta.url), setup);
writeFileSync(new URL("./sql/10_jobs.sql", import.meta.url), jobs);
console.log("wrote sql/00_tables.sql and sql/10_jobs.sql");
